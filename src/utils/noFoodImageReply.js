export const renderContextualNoFoodImageReply = ({ imageSubject, imageCaption } = {}) => {
  const subject = normalize(imageSubject);
  const caption = normalize(imageCaption);
  const detail = `${subject} ${caption}`.trim();
  const paeCalScore = score(detail, PAECAL_SIGNAL_PATTERNS);

  // Pets first: a pet with glasses/accessories is still a pet, not PaeCal.
  if (has(detail, /(แมว|cat|kitten)/i)) return renderPetReply("cat");
  if (has(detail, /(หมา|สุนัข|dog|puppy)/i)) return renderPetReply("dog");
  if (has(detail, /(นก|bird|parrot|นกแก้ว)/i)) return renderPetReply("bird");
  if (has(detail, /(ปลา|fish|goldfish|ปลาทอง)/i)) return renderPetReply("fish");
  if (has(detail, /(หนู|hamster|แฮมสเตอร์|guinea\s*pig|แกสบี้|rabbit|กระต่าย)/i)) return renderPetReply("small");

  if (paeCalScore >= 2) return renderPaeCalMaybeSelfReply();

  if (has(detail, /(photoshop|โฟโต้ชอป|โฟโต้ช็อป|ps\b|adobe\s*photoshop)/i)) {
    return pick([
      "เอ้า Photoshop มาเฉย 555\nอันนี้แปะนับแคลไม่ได้อะ\nส่งของกินมา เดี๋ยวแปะอ่านทรงให้ 👀",
      "Photoshop กินไม่ได้เด้อ 555\nแปะยังลงมื้อให้ไม่ได้\nเอารูปอาหารมาดีกว่า เดี๋ยวดูให้",
      "อันนี้ Photoshop นะ 👀\nไม่ใช่ของกิน แปะยังไม่กล้าจดเป็นมื้อ 555\nส่งจานจริงมาได้เลย",
    ]);
  }

  if (has(detail, /(logo|โลโก้|icon|ไอคอน|app|แอป|โปรแกรม)/i)) {
    return pick([
      "เอ้า อันนี้โลโก้/ไอคอนนะ 555\nแปะนับแคลจากแอปไม่ได้อะ\nส่งของกินมา เดี๋ยวแปะอ่านทรงให้ 👀",
      "ไอคอนแอปกินไม่ได้เด้อ 555\nแปะยังลงมื้อให้ไม่ได้\nเอารูปอาหารมาดีกว่า เดี๋ยวดูให้",
      "อันนี้ดูเป็นโลโก้/แอปนะ 👀\nแปะยังไม่กล้านับเป็นมื้ออาหาร 555\nส่งจานจริงมาได้เลย",
    ]);
  }

  if (has(detail, /(จอ|หน้าจอ|screenshot|screen|คอม|มือถือ|แชต|chat)/i)) {
    return pick([
      "เอ้า อันนี้เหมือนรูปหน้าจอนะ 555\nแปะยังนับแคลไม่ได้อะ\nส่งรูปอาหารจริงมา เดี๋ยวแปะดูให้ 👀",
      "รูปจอใช่มะ 👀\nยังไม่ใช่ของกินที่แปะลงมื้อได้\nเอาจานจริงมา เดี๋ยวจัดให้",
      "แปะเห็นเป็นหน้าจอนะ 555\nยังลงแคลให้ไม่ได้\nส่งรูปอาหารมาอีกทีได้เลย",
    ]);
  }

  if (has(detail, /(คน|หน้า|selfie|เซลฟี่|portrait|รูปคน)/i)) {
    return pick([
      "เอ้า อันนี้รูปคนนะ 555\nถ้าเป็นแปะ ต้องมีแว่นกับผ้าส้มชัด ๆ หน่อย\nส่วนแคล ส่งรูปอาหารมา เดี๋ยวแปะดูให้ 👀",
      "อันนี้เหมือนเซลฟี่นะ 👀\nแปะยังไม่กล้าทึกทักว่าเป็นตัวเอง\nส่งจานที่กินมา เดี๋ยวดูให้",
      "รูปนี้ยังไม่ใช่มื้ออาหารนะ 😅\nแปะยังลงแคลให้ไม่ได้\nส่งรูปอาหารมา เดี๋ยวจัดให้",
    ]);
  }

  if (subject && !has(subject, /(อาหาร|food|meal|เครื่องดื่ม|drink|beverage)/i)) {
    return pick([
      `เอ้า อันนี้เหมือนรูป${subject}นะ 👀\nยังไม่ใช่อาหารที่แปะนับแคลได้\nส่งรูปจานที่กินมา เดี๋ยวแปะจัดให้`,
      `แปะเห็นเป็น${subject}นะ 555\nขอแปะไว้ก่อน ยังไม่ลงมื้อให้\nส่งอาหารจริงมาอีกทีได้เลย`,
      `รูป${subject}มาแบบชัดอยู่ 😂\nแต่ยังไม่ใช่ของกินที่นับแคลได้\nถ่ายจานอาหารมา เดี๋ยวแปะดูให้`,
    ]);
  }

  return pick([
    "เอ้า อันนี้ยังไม่ใช่อาหารนะ 555\nแปะขอแปะไว้ก่อน นับแคลให้ไม่ถนัด\nส่งรูปจานที่กินมา เดี๋ยวแปะจัดให้ 👀",
    "แปะยังไม่เห็นของกินชัด ๆ นะ 👀\nขอรูปอาหารอีกทีได้มะ\nเดี๋ยวแปะดูให้",
    "รูปนี้แปะยังลงมื้อให้ไม่ชัวร์ 😅\nเอาอาหารชัด ๆ อีกนิดนึง\nแปะจัดให้เลย",
  ]);
};
