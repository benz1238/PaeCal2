const pick = (items = []) => items[Math.floor(Math.random() * items.length)] || "";
const normalize = (value = "") => String(value || "").trim();

const has = (text, pattern) => pattern.test(text);

export const renderContextualNoFoodImageReply = ({ imageSubject, imageCaption } = {}) => {
  const subject = normalize(imageSubject);
  const caption = normalize(imageCaption);
  const detail = `${subject} ${caption}`.trim();

  if (has(detail, /(แปะ|แปะแคล|paecal|pae\s*cal|มาสคอต|mascot|ตัวการ์ตูน|cartoon|การ์ตูนผู้ชาย|ผู้ชายใส่แว่น|คนใส่แว่น)/i)) {
    return pick([
      "เอ้า นั่นแปะเอง 555\nรูปนี้ลงแคลไม่ได้ แต่แปะให้ผ่านในหมวดความหล่อแบบมีอายุ 👀\nส่งอาหารมา เดี๋ยวตัวจริงดูให้",
      "ใช่ดิ นั่นแปะเอง 555\nแต่อย่าเอาแปะไปนับแคลนะ ลื้อส่งของกินมา เดี๋ยวแปะอ่านทรงให้",
      "อือหือ รูปแปะมาเอง 👀\nอันนี้ไม่มี kcal มีแต่ความตั้งใจดูแลลื้อ 555\nส่งจานอาหารมา เดี๋ยวแปะดูให้",
    ]);
  }

  if (has(detail, /(photoshop|โฟโต้ชอป|โฟโต้ช็อป|ps\b|adobe|logo|โลโก้|icon|ไอคอน|app|แอป|โปรแกรม)/i)) {
    return pick([
      "เอ้า อันนี้ Photoshop นะ 555\nแปะนับแคลจากโลโก้ไม่ได้อะ\nส่งของกินมา เดี๋ยวแปะอ่านทรงให้ 👀",
      "ไอคอนแอปกินไม่ได้เด้อ 555\nแปะยังลงมื้อให้ไม่ได้\nเอารูปอาหารมาดีกว่า เดี๋ยวดูให้",
      "อันนี้ดูเป็นโลโก้/แอปนะ 👀\nแปะยังไม่กล้านับเป็นมื้ออาหาร 555\nส่งจานจริงมาได้เลย",
    ]);
  }

  if (has(detail, /(แมว|cat|kitten)/i)) {
    return pick([
      "เอ้า แมวมาอีกแล้วเหรอ 555\nน่ารักอยู่ แต่แปะยังลงแคลให้น้องไม่ได้นะ\nถ้าลื้อกินอะไร ส่งจานมา เดี๋ยวแปะดูให้ 👀",
      "เหมียวได้อยู่ 555\nแต่น้องไม่ใช่มื้ออาหารนะ ลื้อส่งของกินมา แปะค่อยนับให้",
      "อันนี้สายแมวชัด ๆ 555\nแปะให้ผ่านหมวดน่ารัก แต่ยังไม่ลงแคลนะ 👀",
    ]);
  }

  if (has(detail, /(หมา|สุนัข|dog|puppy)/i)) {
    return pick([
      "เอ้า น้องหมามา 555\nแปะให้คะแนนความน่ารักก่อน แต่แคลยังไม่ลงนะ\nส่งอาหารของลื้อมา เดี๋ยวแปะดูให้",
      "โฮ่งมาแบบนี้ แปะยิ้มอยู่ 555\nแต่ยังไม่ใช่ของกินนะ ลื้อส่งจานจริงมาได้เลย",
      "น้องหมาได้อยู่ 👀\nแต่แปะนับแคลให้น้องไม่ได้อะ ส่งมื้อของลื้อมาแทน",
    ]);
  }

  if (has(detail, /(จอ|หน้าจอ|screenshot|screen|คอม|มือถือ|แชต|chat)/i)) {
    return pick([
      "เอ้า อันนี้เหมือนรูปหน้าจอนะ 555\nแปะยังนับแคลไม่ได้อะ\nส่งรูปอาหารจริงมา เดี๋ยวแปะดูให้ 👀",
      "รูปจอใช่มะ 👀\nยังไม่ใช่ของกินที่แปะลงมื้อได้\nเอาจานจริงมา เดี๋ยวจัดให้",
      "แปะเห็นเป็นหน้าจอนะ 555\nยังลงแคลให้ไม่ได้\nส่งรูปอาหารมาอีกทีได้เลย",
    ]);
  }

  if (has(detail, /(คน|หน้า|selfie|เซลฟี่|portrait|รูปคน)/i)) {
    return pick([
      "เอ้า อันนี้รูปคนนะ 555\nแปะดูแคลจากหน้าไม่ได้อะ\nส่งรูปอาหารมา เดี๋ยวแปะจัดให้ 👀",
      "อันนี้เหมือนเซลฟี่นะ 👀\nแปะขอแปะไว้ก่อน ยังไม่ใช่อาหาร\nส่งจานที่กินมา เดี๋ยวดูให้",
      "รูปนี้ยังไม่ใช่มื้ออาหารนะ 😅\nแปะยังลงแคลให้ไม่ได้\nส่งรูปอาหารมา เดี๋ยวจัดให้",
    ]);
  }

  if (subject && !has(subject, /(อาหาร|food|meal|เครื่องดื่ม|drink|beverage)/i)) {
    return pick([
      `เอ้า อันนี้เหมือนรูป${subject}นะ 👀\nยังไม่ใช่อาหารที่แปะนับแคลได้\nส่งรูปจานที่กินมา เดี๋ยวแปะจัดให้`,
      `แปะเห็นเป็น${subject}นะ 555\nขอแปะไว้ก่อน ยังไม่ลงมื้อให้\nส่งอาหารจริงมาอีกทีได้เลย`,
      `รูป${subject}มาแบบชัดอยู่ 😂\nแต่ยังไม่ใช่ของกินที่นับแคลได้\nถ่ายจานอาหารมา เดี๋ยวแปะดูให้`,
    ]);
  }

  return pick([
    "เอ้า อันนี้ยังไม่ใช่อาหารนะ 555\nแปะขอแปะไว้ก่อน นับแคลให้ไม่ถนัด\nส่งรูปจานที่กินมา เดี๋ยวแปะจัดให้ 👀",
    "แปะยังไม่เห็นของกินชัด ๆ นะ 👀\nขอรูปอาหารอีกทีได้มะ\nเดี๋ยวแปะดูให้",
    "รูปนี้แปะยังลงมื้อให้ไม่ชัวร์ 😅\nเอาอาหารชัด ๆ อีกนิดนึง\nแปะจัดให้เลย",
  ]);
};
